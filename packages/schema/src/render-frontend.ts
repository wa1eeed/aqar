import {
  categories,
  cities,
  closedStatuses,
  fieldGroups,
  fields,
  nearby,
  offers,
  rentPeriods,
  statuses,
  types,
} from './data';

/**
 * Renders the browser IIFE that sets `window.MZ.schema` with the exact public surface of the
 * original hand-written frontend file (same keys, same helper behaviour).
 */
export function renderFrontendSchema(): string {
  const data = { offers, statuses, closedStatuses, categories, types, rentPeriods, cities, fieldGroups, fields };
  const json = (v: unknown) => JSON.stringify(v, null, 2).replace(/\n/g, '\n  ');

  return `/* =========================================================
   GENERATED — edit packages/schema
   (pnpm schema:frontend). Do not edit this file by hand.

   منزلة العقارية — نموذج البيانات (Schema)
   أنواع العقار، أنواع العرض، الحالات، والحقول حسب النوع والعرض.
   ========================================================= */
window.MZ = window.MZ || {};

(function (MZ) {
  var ALL = '*';

  var schema = ${json(data)};

  /* -------- Helpers -------- */
  function match(list, v) { return list === ALL || list.indexOf(v) !== -1; }

  schema.fieldsFor = function (type, offer) {
    return schema.fields.filter(function (f) { return match(f.types, type) && match(f.offers, offer); });
  };
  schema.field = function (key) {
    for (var i = 0; i < schema.fields.length; i++) if (schema.fields[i].key === key) return schema.fields[i];
    return null;
  };
  schema.statusesFor = function (offer) {
    return Object.keys(schema.statuses).filter(function (s) { return schema.statuses[s].offers.indexOf(offer) !== -1; });
  };
  schema.city = function (id) {
    for (var i = 0; i < schema.cities.length; i++) if (schema.cities[i].id === id) return schema.cities[i];
    return null;
  };
  schema.isClosed = function (status) { return schema.closedStatuses.indexOf(status) !== -1; };

  /* أصناف الخدمات القريبة — تُستخدم مع OpenStreetMap (Overpass) أو مع API الخاص بك */
  schema.nearby = ${json(nearby)};

  MZ.schema = schema;
})(window.MZ);
`;
}
